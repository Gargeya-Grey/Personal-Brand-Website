import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
await db.exec(await readFile(new URL('../data/sql/security_intake.sql', import.meta.url), 'utf8'));
await db.exec('set role service_role');
const digest = (n) => n.toString(16).padStart(64,'0');
const admit = async (client,email,id,weight=1) => (await db.query(
  'select public.security_admit_intake($1,$2,$3,$4) as result', [digest(client),digest(email),digest(id),weight])).rows[0].result;
assert.equal(await admit(1,1,1), 'allowed');
assert.equal(await admit(1,1,1), 'duplicate');
assert.equal(await admit(2,1,2), 'allowed');
assert.equal(await admit(3,1,3), 'allowed');
for(let n=4;n<=6;n++) assert.equal(await admit(n,1,n),'allowed');
assert.equal(await admit(7,1,7), 'denied', 'email budget follows changing clients');
await db.exec('truncate public.security_budgets, public.security_requests');
for (let n=1;n<=5;n++) assert.equal(await admit(1,n,n), 'allowed');
assert.equal(await admit(1,6,6), 'denied', 'client budget follows varied addresses');
await db.exec('truncate public.security_budgets, public.security_requests');
const reservations = await Promise.all(Array.from({length:30},(_,n)=>admit(n+1,n+1,n+1,2)));
assert.equal(reservations.filter(x=>x==='allowed').length,10, 'concurrent varied clients/addresses share global 20-unit ceiling');
const token = digest(999);
const expires = new Date(Date.now()+60000).toISOString();
const consumes = await Promise.all(Array.from({length:10},()=>db.query('select public.security_consume_token($1,$2) as used',[token,expires])));
assert.equal(consumes.filter(x=>x.rows[0].used).length,1,'one-use capability is atomic');
assert.equal((await db.query('select public.security_consume_token($1,now()-interval \'1 second\') as used',[digest(998)])).rows[0].used,false);
await db.exec('set role anon');
await assert.rejects(db.query('select public.security_admit_intake($1,$2,$3,1)',[digest(1),digest(1),digest(1)]), /permission denied/);
await assert.rejects(db.query('select * from public.security_used_tokens'), /permission denied/);
await db.close();
console.log('security SQL PASS: shared admission, duplicate suppression, client/address/global limits, one-use/expired tokens, anonymous denial');
